-- Phase 18: ปิดใช้งานบ้าน (ไม่ลบ) — รันครั้งเดียวใน SQL Editor
-- ลบบ้านทำได้เฉพาะบ้านที่ไม่เคยมีสัญญาเลย (มี FK กันลบ) — บ้านที่เคยมีลูกค้ามาก่อน
-- (แม้ปิดหมดแล้ว) ลบไม่ได้ตลอดไป ต้องมีทาง "เลิกใช้บ้านนี้" โดยไม่ลบประวัติ
-- แก้: เพิ่ม is_active — ปิดใช้งานแล้วไม่ให้เพิ่มลูกค้า/เปิดยอดใหม่ที่บ้านนี้อีก
--     แต่ลูกค้าเดิมยังรับเงิน/ดูรายงานได้ตามปกติจนกว่าจะปิดสัญญาครบ

alter table branches add column if not exists is_active boolean not null default true;
