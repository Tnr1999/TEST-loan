-- Phase 7 — เก็บประวัติ "เคยตาย" (was_lost) บนสัญญา (loans)
-- ════════════════════════════════════════════════════════════
-- ใช้สำหรับฟีเจอร์ "คืนเครดิต": ลูกค้าที่เคยถูกตั้งสถานะ "ตาย" (หายติดต่อ)
-- เมื่อกลับมาจ่าย ต้น+ดอก+ค่าปรับ ครบ → ปิดสัญญา แต่ยังเก็บ flag นี้ไว้
-- เพื่อโชว์ป้าย "คืนเครดิต / เคยตาย" ในประวัติ
--
-- รันครั้งเดียวตอนตั้งระบบ (idempotent — รันซ้ำได้)

alter table loans add column if not exists was_lost boolean not null default false;

-- เติมย้อนหลังให้สัญญาที่ปัจจุบันเป็น "ตาย" อยู่แล้ว
update loans set was_lost = true where status = 'lost';
