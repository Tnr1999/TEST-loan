-- Phase 3: สถานะการโอนเงินให้ลูกค้าใหม่ (รอรับเงิน / รับเงินแล้ว)
-- ลูกค้าใหม่ที่เพิ่งเพิ่มเข้ามา จะติดสถานะ "รอรับเงิน" (disbursed = false)
-- เมื่อแอดมินโอนเงินให้ลูกค้าแล้ว → กดแก้เป็น "รับเงินแล้ว" (disbursed = true)
-- ═══════════════════════════════════════════════════════════

alter table loans add column if not exists disbursed boolean not null default false;

-- สัญญาเดิมทั้งหมดในระบบ ถือว่าโอนเงินให้ลูกค้าไปแล้ว
update loans set disbursed = true;
