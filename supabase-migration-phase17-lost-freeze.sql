-- Phase 17: หยุดคิดดอกทันทีเมื่อลูกค้าสถานะ "ตาย" — รันครั้งเดียวใน SQL Editor
-- เดิม: เปลี่ยนสถานะเป็น "ตาย" แล้วดอกยังวิ่งต่อไปเรื่อยๆ ตามวันที่ผ่านไป
-- (interestDue คำนวณจาก daysBetween(last_collection_date, วันนี้) โดยไม่สนสถานะ)
-- แก้: บันทึก "วันที่ตาย" แล้วแช่แข็งดอกไว้ที่วันนั้น ไม่ให้วิ่งต่อระหว่างรอ Owner ตัดสินใจ
--     (คืนเครดิต / ตัดหนี้สูญ) — ยอดปิด/ยอดคืนเครดิตจะไม่บวมเพิ่มขึ้นทุกวันที่ผ่านไปอีกต่อไป

alter table loans add column if not exists lost_date date;

-- ลูกค้าตายที่มีอยู่แล้วก่อนแก้บั๊กนี้ — ไม่รู้วันที่ตายจริงย้อนหลัง ตั้งเป็นวันนี้
-- (แช่แข็งจากวันที่รัน migration เป็นต้นไป ดีกว่าปล่อยดอกวิ่งต่อไม่มีที่สิ้นสุด)
update loans set lost_date = current_date where status = 'lost' and lost_date is null;
